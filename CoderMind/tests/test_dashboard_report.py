    assert 'id="rpgFrame" src="rpg.html"' not in report_js
    assert "frameElement.srcdoc = RPG_DOCUMENT" in report_js
    assert "contentWindow.d3" not in report_js
    assert "rpgFallback" not in report_js
    assert report_data.startswith("// Generated by CoderMind")
    embedded_rpg = json.loads(
        report_data.split("window.CMIND_RPG_HTML = ", 1)[1]
        .split(";\nwindow.CMIND_REPORT = ", 1)[0]
    )
    payload = json.loads(report_data.split("window.CMIND_REPORT = ", 1)[1].rsplit(";", 1)[0])
    assert payload["workspace"]["name"] == "demo"
    assert embedded_rpg == rpg_html
    assert "const hasChangeData = true;" in rpg_html
    assert "old12345" in rpg_html
    assert "Current Changes" in rpg_html
    assert "@media (max-width: 600px)" in rpg_html
    assert "#search { width: 62px; min-width: 62px" in rpg_html
    assert "'arrow-rel-' + relation" in rpg_html
    assert "drawn relations" in rpg_html
    assert "Directed relations" in rpg_html
    assert "Node fill · code type" in rpg_html
    assert "function / method" in rpg_html
    assert "let cpOpen = true;" in rpg_html
    assert "fill: #e6edf3" in rpg_html
    assert ":root[data-theme=\"light\"] .change-graph-node .node-label" in rpg_html
    assert "<b>${changeNodeGlyph(r.status)}</b>${statusLabel}" in rpg_html
    assert "btn.textContent = cpOpen ? 'Hide changes' : 'Show changes';" in rpg_html
    assert "function dependencyDisplayLabel(node)" in rpg_html
