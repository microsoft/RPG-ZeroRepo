def test_writes_complete_static_report(tmp_path: Path) -> None:
    snapshot = _snapshot()
    outputs = write_dashboard_report(snapshot, tmp_path / "reports")

    for output in (
        outputs.report_html,
        outputs.report_data_js,
        outputs.rpg_html,
        outputs.report_css,
        outputs.report_js,
    ):
        assert output.is_file()
        assert output.stat().st_size > 0

    report_html = outputs.report_html.read_text(encoding="utf-8")
    report_js = outputs.report_js.read_text(encoding="utf-8")
    report_data = outputs.report_data_js.read_text(encoding="utf-8")
    rpg_html = outputs.rpg_html.read_text(encoding="utf-8")

    assert 'src="report-data.js"' in report_html
    assert 'src="assets/report.js"' in report_html
    assert 'href="assets/report.css"' in report_html
    assert "fetch(" not in report_html
    assert "fetch(" not in report_js
    assert 'data-view="features"' not in report_html
    assert 'id="view-features"' not in report_html
    assert "renderFeatures" not in report_js
    assert '"features"' not in report_js
    assert "Feature plan" not in report_js
    assert "Pipeline readiness and stage evidence" in report_js
    assert "no evidence" in report_js
